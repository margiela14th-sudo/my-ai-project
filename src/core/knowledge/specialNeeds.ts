export function specialNeedsKnowledgeText(
  setting: ClassSetting,
  types: DisabilityType[] = [],
  intellectualStage?: string,
): string {
  if (setting === "regular" && types.length === 0) {
    return [
      "## 通常の学級でのユニバーサルデザインと個別の配慮",
      "- 全員に有効な支援（焦点化・視覚化・共有化）を基本とし、個別の配慮が必要な子への支援を別に示す",
      "- 支援の必要な子は仮名（Aさんなど）で書き、具体的な手立てを本時の展開に位置付ける",
    ].join("\n");
  }

  const parts: string[] = [`## 特別支援教育ナレッジ（${CLASS_SETTING_LABELS[setting]}）`];

  if (setting === "specialClass") {
    parts.push(
      "- 特別支援学級では特別の教育課程を編成できる（学校教育法施行規則第138条）。自立活動を取り入れ、知的障害学級では各教科を特別支援学校（知的障害）の各教科に替えることができる",
      "- 個別の指導計画・個別の教育支援計画の目標と本時の目標をつなげて書く",
      "- 交流及び共同学習（通常の学級での学習）との関連があれば示す",
    );
  } else if (setting === "specialSchool") {
    parts.push(
      "- 特別支援学校学習指導要領に基づき、各教科・自立活動・各教科等を合わせた指導（日常生活の指導、生活単元学習、作業学習等）を考慮する",
      "- 複数の教員（T1・T2・T3）の役割分担を指導案に明記する",
    );
  } else if (setting === "resourceRoom") {
    parts.push(
      "- 通級による指導は自立活動の内容を参考に、障害による学習上・生活上の困難の改善・克服を目的とする（各教科の補充指導が中心にならないように）",
      "- 在籍学級の担任との連携（指導内容の共有、在籍学級での般化）を書く",
    );
  }

  if (types.includes("intellectual")) {
    parts.push(
      `- 知的障害の各教科は段階で示される（小学部3段階、中学部2段階）。${intellectualStage ? `本時は「${intellectualStage}」を想定。` : "段階を明示して目標を設定する。"}`,
      "- 学年相当の内容にこだわらず、個々の実態（できていること・もう少しでできること）から目標を立てる",
    );
  }

  parts.push(
    "### 自立活動 6区分27項目",
    Object.entries(JIRITSU_KATSUDO)
      .map(([k, v]) => `- ${k}：${v.map((x, i) => `(${i + 1})${x}`).join(" ")}`)
      .join("\n"),
  );

  for (const t of types) {
    parts.push(`### ${DISABILITY_LABELS[t]}への支援例\n${SUPPORT_EXAMPLES[t].map((x) => `- ${x}`).join("\n")}`);
  }

  parts.push(
    "### 指導案に必ず含めること",
    "- 個別の目標（児童生徒ごと、仮名で）と、それに対応する個別の手立て・評価",
    "- 教材・教具の工夫（具体物、視覚支援、ICT）",
    "- 合理的配慮の内容（なぜその配慮が必要か）",
  );

  return parts.join("\n");
}
