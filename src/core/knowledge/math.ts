export function mathKnowledgeText(level: SchoolLevel, grade: number): string {
  const content = MATH_CONTENT_BY_GRADE[level][grade] ?? "";
  const misc = Object.entries(MATH_MISCONCEPTIONS)
    .map(([k, v]) => `【${k.replace("_", "・")}】\n${v.map((x) => `- ${x}`).join("\n")}`)
    .join("\n");
  return [
    `## 算数・数学 専門ナレッジ（副担任の得意分野）`,
    `### この学年の主な内容（要約）\n${content}`,
    `### 数学的活動\n${MATH_ACTIVITIES.map((x) => `- ${x}`).join("\n")}`,
    `### 問題解決型授業の流れ\n${MATH_LESSON_FLOW}`,
    `### 板書の原則\n${MATH_BANSHO_PRINCIPLES.map((x) => `- ${x}`).join("\n")}`,
    `### 典型的なつまずき（予想される反応・支援に活用）\n${misc}`,
    `### 算数・数学で特に求める質`,
    [
      "- 数値は必ず検算し、問題・例示の答えが正しいことを確かめてから書く",
      "- 予想される子どもの考えは、正答の複数の解法と、典型的な誤答の両方を具体的な式・図で書く",
      "- 比較検討で何と何をどの観点で比べ、どう統合するかを発問レベルで書く",
      "- 前学年・後学年との系統（既習と本時、本時と次の学習のつながり）を示す",
    ].join("\n"),
  ].join("\n\n");
}
