/** 算数・数学の問題解決型授業の基本的な流れ */
export const MATH_LESSON_FLOW = `
1. 問題把握（5〜10分）：既習との違いが際立つ問題を提示し、「何が分かれば解けるか」「今までと何が違うか」を引き出す。
2. めあて（課題）の設定：子どもの言葉から本時の問いを焦点化する（例:「〜はどのように計算すればよいだろうか」）。
3. 見通し：方法（図・式・既習の考え）と結果（およその答え）の見通しをもたせる。
4. 自力解決（10分前後）：机間指導で考えを把握し、取り上げる順序（意図的指名）を決める。つまずいている子へのヒントカードを用意。
5. 比較検討・練り上げ（15分前後）：複数の考えを「同じところ・違うところ」「どの考えでもいえること」で比較し、よりよい（簡潔・明瞭・的確な）方法へ統合する。
6. まとめ：めあてに正対したまとめを、子どもの言葉を生かして書く。
7. 適用問題・振り返り：本時の考えを使って解く。「分かったこと」「次に考えたいこと」を書く（発展的に考える）。
`.trim();

